import numpy as np
from scipy.stats import chi2

# Матриця рангів (експерти × варіанти X1–X5)
data = np.array([
    [1, 4, 1, 2, 5],
    [2, 5, 1, 4, 4],
    [1, 5, 2, 3, 4],
    [2, 3, 3, 4, 5],
    [2, 3, 2, 1, 5]
])

m, n = data.shape  # m — кількість експертів, n — кількість альтернатив

# 1. Обчислення суми рангів для кожної альтернативи
R = np.sum(data, axis=0)
print("Суми рангів:", R)

# Визначення найкращого варіанту (мінімальна сума рангів)
best_index = np.argmin(R)
print(f"Найкращий варіант: X{best_index + 1}")

# 2. Середнє значення сум рангів
R_mean = np.mean(R)

# 3. Обчислення S — суми квадратів відхилень
S = np.sum((R - R_mean) ** 2)

# 4. Урахування однакових рангів (зв'язків)
T = 0
for row in data:
    _, counts = np.unique(row, return_counts=True)
    for t in counts:
        if t > 1:
            T += (t**3 - t)

# 5. Обчислення коефіцієнта конкордації Кендалла W
W = 12 * S / (m**2 * (n**3 - n) - m * T)
print(f"Коефіцієнт конкордації W = {W:.4f}")

# 6. Перевірка значущості (критерій Пірсона χ²)
chi_square = m * (n - 1) * W
df = n - 1  # ступені свободи
chi_critical = chi2.ppf(0.95, df)

print(f"χ² спостережуване = {chi_square:.4f}")
print(f"χ² критичне (γ=0.95) = {chi_critical:.4f}")

# 7. Висновок щодо узгодженості
if chi_square > chi_critical:
    print("Узгодженість значуща, оцінки можна узагальнювати")
else:
    print("Узгодженість НЕ значуща, узагальнення недоцільне")